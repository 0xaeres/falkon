// External-oracle mode: use an already-registered v6 deployment as the oracle and run the clone
// over exactly the repos it indexes.
//   node parity/external-oracle.mjs <v6 compose.yml>
// Reads the v6 compose file's read-only repo mounts (host:/repos/<dir>:ro), names each repo the
// way v6 does for file:// connections (origin URL host + path, minus .git), and writes:
//   parity/.gen/external/clone.config.json   clone config with one local connection per repo
//   parity/.gen/external/compose.yml         clone-only stack (web :3200, zoekt 127.0.0.1:16071)
// Then: docker compose -f parity/.gen/external/compose.yml up -d --build
//       V6_URL=http://localhost:3000 V6_API_KEY_FILE=<path> node parity/run.mjs --queries parity/queries.openmrs.json
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const here = path.dirname(new URL(import.meta.url).pathname);
const composePath = path.resolve(process.argv[2] ?? "");
if (!process.argv[2] || !fs.existsSync(composePath)) {
  console.error("usage: node parity/external-oracle.mjs <path to v6 compose.yml>");
  process.exit(2);
}

// Volume lines look like `- /host/path:/repos/name:ro`; a YAML parser is not worth a dependency here.
const mounts = [...fs.readFileSync(composePath, "utf8").matchAll(/^\s*-\s*(\/[^:\s]+):(\/repos\/[^:\s]+)(?::ro)?\s*$/gm)].map((m) => ({
  host: m[1],
  container: m[2],
}));
if (!mounts.length) throw new Error(`no /repos/* mounts found in ${composePath}`);

/** Mirrors v6 compileGenericGitHostConfig_file: host (with explicit port) + decoded path, minus .git. */
function v6RepoName(origin) {
  const scp = /^[^@/]+@([^:/]+):(.+)$/.exec(origin); // git@host:owner/repo.git
  let host;
  let pathname;
  if (scp) {
    host = scp[1];
    pathname = "/" + scp[2];
  } else {
    const u = new URL(origin);
    host = /^[a-z+]+:\/\/(?:[^@/]*@)?([^/]+)/i.exec(origin)?.[1] ?? u.host;
    pathname = u.pathname;
  }
  return path.posix.join(host, decodeURIComponent(pathname).replace(/\.git$/, ""));
}

const repos = [];
for (const m of mounts) {
  let origin;
  try {
    origin = execFileSync("git", ["-C", m.host, "config", "--get", "remote.origin.url"], { encoding: "utf8" }).trim();
  } catch {
    console.warn(`skip ${m.host}: no remote.origin.url (v6 skips it too)`);
    continue;
  }
  repos.push({ ...m, name: v6RepoName(origin) });
}

const out = path.join(here, ".gen/external");
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(
  path.join(out, "clone.config.json"),
  // Same shape as the v6 config: one file:// connection per mounted repo (v6 itself uses a glob).
  JSON.stringify({ connections: Object.fromEntries(repos.map((r, i) => [`repo-${i}`, { type: "git", url: `file://${r.container}` }])) }, null, 2),
);

const vol = repos.map((r) => `      - ${r.host}:${r.container}:ro`).join("\n");
const repoRoot = path.resolve(here, "..");
fs.writeFileSync(
  path.join(out, "compose.yml"),
  `# Generated by parity/external-oracle.mjs from ${composePath}
name: sbc-parity-external
x-git-safe: &gitsafe
  GIT_CONFIG_COUNT: "1"
  GIT_CONFIG_KEY_0: safe.directory
  GIT_CONFIG_VALUE_0: "*"
services:
  sbc-postgres:
    image: postgres:17-alpine
    environment: { POSTGRES_USER: sbc, POSTGRES_PASSWORD: sbc, POSTGRES_DB: sbc }
    healthcheck: { test: ["CMD-SHELL", "pg_isready -U sbc"], interval: 3s, retries: 30 }
  sbc-redis:
    image: redis:7-alpine
    healthcheck: { test: ["CMD", "redis-cli", "ping"], interval: 3s, retries: 30 }
  sbc-backend: &sbc
    image: sourcebot-clone-app
    build: { context: ${repoRoot}, dockerfile: docker/Dockerfile }
    command: sh -c "pnpm --filter @sbc/db push && pnpm --filter @sbc/backend start"
    environment:
      <<: *gitsafe
      DATABASE_URL: postgresql://sbc:sbc@sbc-postgres:5432/sbc
      REDIS_URL: redis://sbc-redis:6379
      DATA_DIR: /data
      CONFIG_PATH: /config/config.json
      ZOEKT_URL: http://sbc-zoekt:6070
      AUTH_URL: http://localhost:3200
    volumes:
      - sbcdata:/data
      - ${path.join(out, "clone.config.json")}:/config/config.json:ro
${vol}
    depends_on: { sbc-postgres: { condition: service_healthy }, sbc-redis: { condition: service_healthy } }
  sbc-zoekt:
    <<: *sbc
    command: zoekt-webserver -index /data/index -rpc -listen :6070
    ports: ["127.0.0.1:16071:6070"]
    depends_on: [sbc-backend]
  sbc-web:
    <<: *sbc
    command: pnpm --filter @sbc/web start
    ports: ["3200:3000"]
    depends_on: [sbc-backend, sbc-zoekt]
volumes:
  sbcdata:
`,
);
console.log(`${repos.length}/${mounts.length} repos -> ${path.relative(process.cwd(), out)}/{clone.config.json,compose.yml}`);
for (const r of repos.slice(0, 5)) console.log(`  ${r.name}`);
